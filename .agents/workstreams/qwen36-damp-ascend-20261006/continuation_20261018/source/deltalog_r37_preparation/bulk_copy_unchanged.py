"""Default-off exact byte copying from the frozen R37 repair1 package index.

The two destination roots must both be absent. Only declared unchanged original
files are copied; templates, bound manifests and command packets are excluded.
Changed UTF8 content remains the responsibility of the structured patch writer.
No source tree, output or ledger is generated by this module at import time.
"""
import sys
sys.dont_write_bytecode = True

import argparse
import contextlib
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import stat

TRANSPORT_BYTES = 9812
TRANSPORT_SHA256 = 'e568fb78bbb81ae73a7a081ef1a17a623f34bda76112967e5e42877331a9e524'
PREP = '/cache/cch/qwen36-paper-preparation-20261007/lowbit/'
EXPECTED_ROOTS = {
    'model': PREP + 'deltalog-first-real-decode-owned-renew24h-v1-101-repair37-closed-admission-20261018-001',
    'early': PREP + 'deltalog-early-software-owned-renew24h-v1-37-closed-admission',
}
SCHEMA = 'deltalog.r37-exact-unchanged-byte-copy/v1'
CAP = 4 * 1024 * 1024
O_DIR = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW


def need(value, reason):
    if not value:
        raise ValueError(reason)


def wire(value):
    return (json.dumps(value, sort_keys=True, separators=(',', ':'),
                       allow_nan=False, ensure_ascii=False) + '\n').encode('utf8')


def ref(path, raw):
    return dict(path=str(path), bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest())


def ordinary_path(value):
    need(type(value) is str, 'exact string path')
    path = Path(value)
    need(path.is_absolute() and str(path) == value and '..' not in path.parts,
         'exact absolute ordinary path')
    return path


def ref3(value):
    need(type(value) is dict and set(value) == {'path', 'bytes', 'sha256'},
         'exact Ref3')
    ordinary_path(value['path'])
    need(type(value['bytes']) is int and 0 <= value['bytes'] <= CAP
         and type(value['sha256']) is str and len(value['sha256']) == 64
         and all(c in '0123456789abcdef' for c in value['sha256']),
         'bounded exact file bytes and SHA256')
    return value


def key(value):
    return (value.st_dev, value.st_ino, value.st_mode, value.st_size,
            value.st_mtime_ns, value.st_ctime_ns)


@contextlib.contextmanager
def directory(path):
    """Open every existing directory component without following a symlink."""
    path = ordinary_path(str(path))
    fd = os.open('/', O_DIR)
    try:
        for part in path.parts[1:]:
            next_fd = os.open(part, O_DIR, dir_fd=fd)
            os.close(fd)
            fd = next_fd
        yield fd
    finally:
        os.close(fd)


def fingerprint(stream, expected):
    stream.seek(0)
    raw = stream.read(expected['bytes'] + 1)
    need(len(raw) == expected['bytes']
         and hashlib.sha256(raw).hexdigest() == expected['sha256'],
         'complete exact file bytes: ' + expected['path'])
    return raw


@contextlib.contextmanager
def source_stream(expected):
    expected = ref3(expected)
    path = Path(expected['path'])
    with directory(path.parent) as parent_fd:
        before = os.stat(path.name, dir_fd=parent_fd, follow_symlinks=False)
        need(stat.S_ISREG(before.st_mode), 'ordinary regular source leaf')
        fd = os.open(path.name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=parent_fd)
        with os.fdopen(fd, 'rb') as stream:
            need(key(before) == key(os.fstat(stream.fileno())), 'same opened source inode')
            fingerprint(stream, expected)
            need(key(before) == key(os.fstat(stream.fileno())), 'stable source before copying')
            stream.seek(0)
            yield stream
            fingerprint(stream, expected)
            after = os.stat(path.name, dir_fd=parent_fd, follow_symlinks=False)
            need(key(before) == key(os.fstat(stream.fileno())) == key(after),
                 'complete stable source before and after copying')
    # Also prove that the ordinary pathname still resolves to the same leaf.
    with directory(path.parent) as parent_fd:
        after_path = os.stat(path.name, dir_fd=parent_fd, follow_symlinks=False)
        need(key(before) == key(after_path), 'unchanged ordinary source pathname')


def checked(expected):
    with source_stream(expected) as stream:
        return fingerprint(stream, expected)


def load_transport(transport_ref):
    ref3(transport_ref)
    need(transport_ref['bytes'] == TRANSPORT_BYTES
         and transport_ref['sha256'] == TRANSPORT_SHA256,
         'only frozen reviewed repair1 transport')
    raw = checked(transport_ref)
    spec = importlib.util.spec_from_loader('_r37_copy_transport', loader=None)
    module = importlib.util.module_from_spec(spec)
    module.__file__ = transport_ref['path']
    exec(compile(raw, transport_ref['path'], 'exec'), module.__dict__)
    checked(transport_ref)
    return module


def excluded(name):
    leaf = Path(name).name
    return leaf in {'SOURCE_TEMPLATE.json', 'SOURCE_MANIFEST.json', 'SOURCE_BOUND.json'} \
        or leaf.startswith('COMMANDS')


def select_copies(aliases, entries, original_roots):
    need(set(aliases) == set(entries) == set(original_roots) == {'model', 'early'},
         'exact two declared source and target trees')
    copies, pending = {}, {}
    for alias, root in sorted(aliases.items()):
        ordinary_path(root)
        copies[alias], pending[alias] = [], []
        names = set()
        for entry in entries[alias]:
            name = entry['relative_name']
            need(type(name) is str and name == str(Path(name))
                 and not Path(name).is_absolute() and '..' not in Path(name).parts
                 and name not in names, 'distinct exact declared relative filenames')
            names.add(name)
            target = ref3(entry['ref'])
            need(target['path'] == root + '/' + name, 'exact target from complete inventory')
            original = entry['unchanged_original_ref']
            if original is None or excluded(name):
                pending[alias].append(name)
                continue
            ref3(original)
            need(original['path'] == original_roots[alias] + '/' + name
                 and original['bytes'] == target['bytes']
                 and original['sha256'] == target['sha256']
                 and entry['transfer'] == 'copy-exact-original',
                 'declared exact original bytes only')
            copies[alias].append(dict(relative_name=name, original_ref=original, ref=target))
    need(all(copies.values()), 'nonempty declared pure byte-copy subsets')
    return copies, pending


def absent_roots(aliases):
    roots = [ordinary_path(root) for root in aliases.values()]
    need(len(set(roots)) == 2 and roots[0].parent == roots[1].parent,
         'two distinct fresh sibling roots')
    with directory(roots[0].parent) as parent_fd:
        for root in roots:
            try:
                os.stat(root.name, dir_fd=parent_fd, follow_symlinks=False)
            except FileNotFoundError:
                continue
            raise ValueError('both target roots must be wholly absent: ' + str(root))


@contextlib.contextmanager
def destination(root_fd, name):
    parts = Path(name).parts
    fd = os.dup(root_fd)
    try:
        for part in parts[:-1]:
            try:
                os.mkdir(part, 0o700, dir_fd=fd)
            except FileExistsError:
                pass
            next_fd = os.open(part, O_DIR, dir_fd=fd)
            os.close(fd)
            fd = next_fd
        target_fd = os.open(parts[-1], os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                            0o600, dir_fd=fd)
        with os.fdopen(target_fd, 'w+b') as stream:
            yield stream
    finally:
        os.close(fd)


def inventory_check(root, selected):
    files, directories = set(), set()
    expected_files = {entry['relative_name'] for entry in selected}
    expected_directories = set()
    for name in expected_files:
        for parent in Path(name).parents:
            if str(parent) != '.':
                expected_directories.add(str(parent))
    for current, child_dirs, child_files in os.walk(root, followlinks=False):
        for name in child_dirs:
            path = Path(current) / name
            need(stat.S_ISDIR(path.lstat().st_mode), 'ordinary copied directory')
            directories.add(str(path.relative_to(root)))
        for name in child_files:
            path = Path(current) / name
            need(stat.S_ISREG(path.lstat().st_mode), 'ordinary copied file')
            files.add(str(path.relative_to(root)))
    need(files == expected_files and directories == expected_directories,
         'exact copied inventory; no extra or missing file/directory')
    for entry in selected:
        checked(entry['ref'])


def copy_exact(aliases, copies):
    """Only raw bytes; caller has already authenticated the complete package."""
    absent_roots(aliases)
    for selected in copies.values():
        for entry in selected:
            checked(entry['original_ref'])
    # Recheck both roots after all source-byte preflight reads, before mkdir.
    absent_roots(aliases)
    parent = Path(next(iter(aliases.values()))).parent
    with directory(parent) as parent_fd:
        for alias, root in sorted(aliases.items()):
            os.mkdir(Path(root).name, 0o700, dir_fd=parent_fd)
        for alias, root in sorted(aliases.items()):
            with directory(root) as root_fd:
                for entry in copies[alias]:
                    with source_stream(entry['original_ref']) as source:
                        with destination(root_fd, entry['relative_name']) as target:
                            # O_EXCL above guarantees no implicit overwrite or
                            # truncation. copyfileobj performs a pure byte copy.
                            shutil.copyfileobj(source, target, length=65536)
                            target.flush()
                            os.fsync(target.fileno())
                            fingerprint(target, entry['ref'])
    # A failed run keeps the partial roots for review; it never deletes them.
    for alias, root in sorted(aliases.items()):
        inventory_check(Path(root), copies[alias])


def emit(value):
    raw = wire(value)
    need(len(raw) <= 128 * 1024, 'bounded copy receipt')
    sys.stdout.buffer.write(raw)
    sys.stdout.buffer.flush()


def main():
    parser = argparse.ArgumentParser(allow_abbrev=False)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--plan', action='store_true')
    mode.add_argument('--copy', action='store_true')
    parser.add_argument('--transport-ref')
    parser.add_argument('--generator-ref')
    parser.add_argument('--patch-manifest-ref')
    parser.add_argument('--expected-package-id')
    args = parser.parse_args()
    if not (args.plan or args.copy):
        emit(dict(schema=SCHEMA, enabled=False, read_only=True, NPU=False,
                  model_source_created=False, qualified=False))
        return 0
    need(args.transport_ref and args.generator_ref and args.patch_manifest_ref
         and args.expected_package_id, 'three exact source Refs and reviewed package_id required')
    transport_ref = json.loads(args.transport_ref)
    generator_ref = json.loads(args.generator_ref)
    patch_ref = json.loads(args.patch_manifest_ref)
    transport = load_transport(transport_ref)
    preparer = transport.load_generator(generator_ref)
    bundle = preparer.prepare(patch_ref, emit=True)
    aliases, refs, entries = transport.inventory(preparer, bundle)
    need(aliases == EXPECTED_ROOTS, 'only two exact reviewed R37 preparation roots')
    material = dict(generator_ref=generator_ref, patch_manifest_ref=patch_ref, all_file_refs=refs)
    package_id = hashlib.sha256(transport.wire(material)).hexdigest()
    need(package_id == args.expected_package_id, 'same complete authenticated repair1 package')
    copies, pending = select_copies(aliases, entries,
                                   dict(model=preparer.MODEL_OLD, early=preparer.EARLY_OLD))
    absent_roots(aliases)
    value = dict(schema=SCHEMA, package_id=package_id, transport_ref=transport_ref,
                 generator_ref=generator_ref, patch_manifest_ref=patch_ref,
                 mode='copy' if args.copy else 'plan', tree_roots=aliases,
                 copy_counts={k: len(v) for k, v in copies.items()},
                 copy_bytes={k: sum(e['ref']['bytes'] for e in v) for k, v in copies.items()},
                 exact_copy_plan_sha256=hashlib.sha256(wire(copies)).hexdigest(),
                 pending_structured_patch_files=pending,
                 all_target_file_refs_sha256=hashlib.sha256(transport.wire(refs)).hexdigest(),
                 read_only=not args.copy, source_tree_copy_complete=False,
                 all_copied_refs_finally_rehashed=False, source_text_generated=False,
                 model_source_created=False, NPU=False, qualified=False)
    if args.copy:
        copy_exact(aliases, copies)
        value['source_tree_copy_complete'] = True
        value['all_copied_refs_finally_rehashed'] = True
    transport.checked_generator(generator_ref)
    preparer.checked(patch_ref)
    checked(transport_ref)
    emit(value)
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (ValueError, KeyError, TypeError, OSError, UnicodeError) as error:
        emit(dict(schema=SCHEMA, error=type(error).__name__, reason=str(error)[:3000],
                  partial_roots_retained=True, source_tree_copy_complete=False,
                  model_source_created=False, NPU=False, qualified=False))
        raise SystemExit(2)
