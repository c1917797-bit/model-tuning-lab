"""Source-only faithful-axis KIVI QK/AV candidate. Import is stdlib/default OFF.
No installer/controller. Compiled Ascend identity/numerics/model authority pending.
Factory receives the actual torch/triton/tl objects only after MAIN qualification.
"""
import os

ENV = "QWEN36_KIVI_PACKED_QKAV_SOURCE_CANDIDATE"

def _bind_jit_tl(actual_tl):
    # Triton resolves kernel names in fn.__globals__, not factory locals.
    # setdefault preserves the first binding; a different backend is rejected.
    if globals().setdefault("tl", actual_tl) is not actual_tl:
        raise ValueError("incompatible Triton language global rebinding")

def build(torch, triton, tl, *, device_properties, get_format, qualify):
    if os.environ.get(ENV) != "1":
        raise RuntimeError("KIVI packed QKAV defaults OFF")
    # Caller must independently consume the source/compile/device lease receipt.
    # This callback is not a model/numeric permission generated by this file.
    qualify()
    if not callable(get_format):
        raise ValueError("actual top-level torch_npu format getter required")
    aic = device_properties.get("num_aicore")
    vec = device_properties.get("num_vectorcore")
    if type(aic) is not int or type(vec) is not int or not (0 < aic <= 65535 and 0 < vec <= 65535):
        raise ValueError("actual core properties; no typical-value fallback")

    _bind_jit_tl(tl)

    @triton.jit
    def qk(Q, KC, KS, KM, KT, KP, CT, S,
           B: tl.constexpr, H: tl.constexpr, LMAX: tl.constexpr,
           PMAX: tl.constexpr, BITS: tl.constexpr, CORES: tl.constexpr):
        # One task owns 16 query heads x 32 logical keys. No GM dequant K.
        tasks = B * tl.cdiv(H, 16) * tl.cdiv(LMAX, 32)
        hn = tl.arange(0, 16)
        dn = tl.arange(0, 256)
        tn = tl.arange(0, 32)
        for task in range(tl.program_id(0), tasks, CORES):
            nt = tl.cdiv(LMAX, 32)
            hb = (task // nt) % tl.cdiv(H, 16)
            row = task // (nt * tl.cdiv(H, 16))
            token = task % nt * 32 + tn
            head = hb * 16 + hn
            length = tl.load(CT + row * 4)
            prefix = tl.load(CT + row * 4 + 1)
            slot = tl.load(CT + row * 4 + 3)
            packed = (token < prefix) & (token < length)
            page = tl.load(KP + row * PMAX + token // 128, mask=packed, other=0)
            local = token % 128
            word = tl.load(KC + page[:, None] * (128 // (32 // BITS) * 256)
                           + (local // (32 // BITS))[:, None] * 256 + dn[None, :],
                           mask=packed[:, None], other=0).to(tl.uint32)
            code = (word >> ((local % (32 // BITS)) * BITS)[:, None]) & ((1 << BITS) - 1)
            scale = tl.load(KS + page[:, None] * 1024 + (local // 32)[:, None] * 256 + dn[None, :],
                            mask=packed[:, None], other=0)
            minimum = tl.load(KM + page[:, None] * 1024 + (local // 32)[:, None] * 256 + dn[None, :],
                              mask=packed[:, None], other=0)
            # Explicit two A16 rounding points; FP fusion disabled at launch.
            mul = (code.to(tl.int32).to(tl.float32) * scale.to(tl.float32)).to(KT.dtype.element_ty, fp_downcast_rounding="rtne")
            decoded = (mul.to(tl.float32) + minimum.to(tl.float32)).to(KT.dtype.element_ty, fp_downcast_rounding="rtne")
            residual_mask = (token >= prefix) & (token < length)
            tail = tl.load(KT + slot * 128 * 256 + (token - prefix)[:, None] * 256 + dn[None, :],
                           mask=residual_mask[:, None], other=0)
            key = tl.where(packed[:, None], decoded, tail)
            query = tl.load(Q + row * H * 256 + head[:, None] * 256 + dn[None, :],
                            mask=(head < H)[:, None], other=0)
            logits = tl.dot(query, tl.trans(key)).to(Q.dtype.element_ty, fp_downcast_rounding="rtne")
            # Existing compact reader's A16 QK then A16 scale; D256 scale=1/16.
            logits = (logits.to(tl.float32) * 0.0625).to(Q.dtype.element_ty, fp_downcast_rounding="rtne")
            tl.store(S + row * H * LMAX + head[:, None] * LMAX + token[None, :], logits,
                     mask=(head < H)[:, None] & (token < length)[None, :])

    @triton.jit
    def softmax(S, CT, P, B: tl.constexpr, H: tl.constexpr,
                LMAX: tl.constexpr, CORES: tl.constexpr):
        ix = tl.arange(0, 1024)
        for task in range(tl.program_id(0), B * H, CORES):
            row = task // H
            length = tl.load(CT + row * 4)
            maximum = tl.full((), -float("inf"), tl.float32)
            for start in range(0, length, 1024):
                token = start + ix
                score = tl.load(S + task * LMAX + token, mask=token < length, other=-float("inf")).to(tl.float32)
                maximum = tl.maximum(maximum, tl.max(score, 0))
            total = tl.full((), 0.0, tl.float32)
            for start in range(0, length, 1024):
                token = start + ix
                score = tl.load(S + task * LMAX + token, mask=token < length, other=-float("inf")).to(tl.float32)
                total += tl.sum(tl.exp(score - maximum), 0)
            for start in range(0, length, 1024):
                token = start + ix
                score = tl.load(S + task * LMAX + token, mask=token < length, other=-float("inf")).to(tl.float32)
                prob = (tl.exp(score - maximum) / total).to(P.dtype.element_ty, fp_downcast_rounding="rtne")
                tl.store(P + task * LMAX + token, prob, mask=token < length)

    @triton.jit
    def av(P, VC, VS, VM, VT, VR, CT, O,
           B: tl.constexpr, H: tl.constexpr, LMAX: tl.constexpr,
           BITS: tl.constexpr, CORES: tl.constexpr):
        # Vector reduction, not FP32 dot/HF32. One task: H8 x D32, token tiles32.
        hn = tl.arange(0, 8)
        tn = tl.arange(0, 32)
        dn = tl.arange(0, 32)
        tasks = B * tl.cdiv(H, 8) * 8
        for task in range(tl.program_id(0), tasks, CORES):
            cb = task % 8
            hb = (task // 8) % tl.cdiv(H, 8)
            row = task // (8 * tl.cdiv(H, 8))
            head = hb * 8 + hn
            channel = cb * 32 + dn
            length = tl.load(CT + row * 4)
            prefix = tl.load(CT + row * 4 + 2)
            slot = tl.load(CT + row * 4 + 3)
            accum = tl.zeros((8, 32), dtype=tl.float32)
            for start in range(0, length, 32):
                token = start + tn
                packed = (token < prefix) & (token < length)
                record = tl.load(VR + row * LMAX + token, mask=packed, other=0)
                word = tl.load(VC + record[:, None] * (256 // (32 // BITS)) + channel[None, :] // (32 // BITS),
                               mask=packed[:, None], other=0).to(tl.uint32)
                code = (word >> ((channel % (32 // BITS)) * BITS)[None, :]) & ((1 << BITS) - 1)
                scale = tl.load(VS + record[:, None] * 8 + channel[None, :] // 32, mask=packed[:, None], other=0)
                minimum = tl.load(VM + record[:, None] * 8 + channel[None, :] // 32, mask=packed[:, None], other=0)
                mul = (code.to(tl.int32).to(tl.float32) * scale.to(tl.float32)).to(VT.dtype.element_ty, fp_downcast_rounding="rtne")
                decoded = (mul.to(tl.float32) + minimum.to(tl.float32)).to(VT.dtype.element_ty, fp_downcast_rounding="rtne")
                tail_mask = (token >= prefix) & (token < length)
                tail = tl.load(VT + slot * 129 * 256 + (token - prefix)[:, None] * 256 + channel[None, :],
                               mask=tail_mask[:, None], other=0)
                value = tl.where(packed[:, None], decoded, tail).to(tl.float32)
                prob = tl.load(P + row * H * LMAX + head[:, None] * LMAX + token[None, :],
                               mask=(head < H)[:, None] & (token < length)[None, :], other=0).to(tl.float32)
                weighted = prob[:, :, None] * value[None, :, :]
                accum += tl.sum(weighted, axis=1)
            tl.store(O + row * H * 256 + head[:, None] * 256 + channel[None, :],
                     accum.to(O.dtype.element_ty, fp_downcast_rounding="rtne"), mask=(head < H)[:, None])

    class ModelNew(torch.nn.Module):
        def __init__(self):
            super().__init__()
            self.qk = qk
            self.softmax = softmax
            self.av = av
            self.aic = aic
            self.vec = vec

        def forward(self, q, pool, metadata):
            # metadata.assert_live uses actual ReadView/Request/arena identities.
            metadata.assert_live()
            if metadata.graph:
                raise ValueError("FULL capture/replay registration not implemented")
            b, h, d = q.shape
            if (b, h, d) != (metadata.batch, 6, 256):
                raise ValueError("actual Qwen TP4 Q6/KV1/D256 only; no guessed GQA")
            if q.dtype not in (torch.float16, torch.bfloat16) or q.device.type != "npu" or not q.is_contiguous() or get_format(q) != 2:
                raise ValueError("actual contiguous ND A16 NPU query")
            if pool is not metadata.pool:
                raise ValueError("actual arena pool identity")
            metadata.assert_tensors(q, get_format)
            scores = torch.empty((b, h, metadata.max_length), dtype=q.dtype, device=q.device)
            probs = torch.empty_like(scores)
            result = torch.empty_like(q)
            self.qk[(self.aic,)](q, pool["key_codes"], pool["key_scales"], pool["key_minima"],
                pool["key_residual"], metadata.kpages, metadata.controls, scores,
                b, h, metadata.max_length, metadata.max_pages, metadata.bits, self.aic, enable_fp_fusion=False)
            self.softmax[(self.vec,)](scores, metadata.controls, probs,
                b, h, metadata.max_length, self.vec, enable_fp_fusion=False)
            self.av[(self.vec,)](probs, pool["value_codes"], pool["value_scales"], pool["value_minima"],
                pool["value_residual"], metadata.vrecords, metadata.controls, result,
                b, h, metadata.max_length, metadata.bits, self.vec, enable_fp_fusion=False)
            # Asynchronous writes need real consumer/caller completion before finish/recycle.
            metadata.assert_live()
            return result

    return ModelNew

