"""DEFAULT-OFF adapter to the EXACT frozen before-bind worker factory.
No copied controller or native allocator. Actual owner/compiled/numeric qualification
is injected by the existing MAIN-owned caller; missing rejects, not admission here.
"""
import functools
import json
import os

PREBIND_SHA="fb98cb828319eed75de3d7be0bfe82c04404d9f91eb355431dc23dd6492a94bf"
ADAPTER_SHA="984a5c8b470026d94c456833b9706da14baac4a977120cd818086226617297b1"
FIELDS_SHA="77b678af5eea524c59405d98a3681415810e2e77b7f8cf9cde9fd241b28d4157"
RAW_JOURNAL_SHA="695e77632c578389f8823bd0ee98b29239cc6dfde6d5c982500ba0623a383229"

def need(v,m):
    if not v:raise ValueError(m)

def make_worker(native_worker_cls,mods,adapter,prebind,torch,torch_npu,tp,kv_spec,context,*,
                layout_owner,layout_owner_ref,layout_mf,post_owner,post_owner_ref,
                installer,spans,book,formal,producer,kernel,metadata,journal_module,source_refs,
                device_properties,qualify,ingress_bindings=None,capture_raw=False,raw_root=None,
                provenance=None,first_decode_capture_only=False,raw_journal_module=None,
                resolve_post_owner=None,finish_module=None,publish_final=None,
                provider_initialize=None,provider_state=None,explicit_geometry=None):
    """Existing explicit owned bootstrap calls this in each real worker process.
    Returns a native subclass with original before-bind capture and actual output
    installation. OFF returns original class before reads/imports/tensor effects.
    """
    if os.environ.get(installer.FLAG)!="1":return native_worker_cls
    installer.callable_pin(prebind.make_worker,PREBIND_SHA)
    installer.callable_pin(adapter.Collector,ADAPTER_SHA)
    need(callable(provider_initialize) and type(provider_state)is dict and explicit_geometry is not None,
         "explicit provider initializer/state/independent geometry required")
    installer.callable_pin(explicit_geometry.guard_current,FIELDS_SHA)
    installer.callable_pin(provider_initialize,source_refs["explicit_provider"]["sha256"])
    need(callable(qualify) and type(device_properties) is dict and type(source_refs) is dict,
         "actual existing owner qualifier, compiled device properties and exact source Refs")
    need(type(capture_raw) is bool and (not capture_raw or raw_root is not None),
         "explicit independent raw capture scope")
    need(type(first_decode_capture_only) is bool and (not first_decode_capture_only or capture_raw),
         "first-decode diagnostic requires explicit raw capture; never performance permission")
    if capture_raw:
        need(provenance is not None,"original full prefill provenance is required for model raw capture")
        installer.callable_pin(provenance.capture_tiles,installer.PROVENANCE_SHA)
        need(raw_journal_module is not None,"source-bound first-decode Ref index required")
        installer.callable_pin(raw_journal_module.FirstDecodeJournal,RAW_JOURNAL_SHA)
    need(ingress_bindings is not None,"real assignment/input/owner bindings required, no future IDs")
    need(finish_module is not None and callable(publish_final),"actual native-finished drain hook, not HTTP DONE")
    installer.callable_pin(type(ingress_bindings),installer.INGRESS_SHA)
    qualify() # Source/compile/numerical/owner/resource evidence, never generated by this adapter.
    for name,module in (("kernel",kernel),("metadata",metadata),("lifecycle",mods["lifecycle"]),("callback",mods["callback"])):
        need(source_refs[name]["sha256"]==installer.CRITICAL_SHA[name],"exact frozen critical algorithm bytes")
        producer.source(module,source_refs[name])
    need("triton" in mods and "tl" in mods,"actual qualified deployed compiler module closure required")
    selected_owner={}
    def validate_post(owner,ref):
        need(json.loads(installer.bound(ref))==owner
             and owner["schema"]=="kivi.packed-qwen-install-input/v1"
             and owner["run_authority"] is False and owner["model_ready"] is False,
             "actual immutable initialized named adaptation input, not permission")
        for name in ("actual_assignment_protocol_ref","capacity_receipt_ref",
                     "external_owner_authority_ref","compiled_numeric_qualification_ref"):
            installer.bound(owner[name])
        selected_owner.update(owner=owner,ref=ref)
    if resolve_post_owner is None:
        validate_post(post_owner,post_owner_ref)
        initialized_resolver=None
    else:
        need(post_owner is post_owner_ref is None and callable(resolve_post_owner),
             "one source-bound actual initialized resolver, not guessed static geometry")
        def initialized_resolver(*args):
            owner,ref=resolve_post_owner(*args)
            validate_post(owner,ref)
            return owner,ref
    class PackedInstallBridge:
        FLAG=installer.FLAG
        def install(self,runner,actual_mods,actual_adapter,t,npu,actual_tp,forward_context,*,
                    owner,owner_ref,event,event_ref,regions,publish,layout_final_ref=None):
            need(actual_mods is mods and actual_adapter is adapter and t is torch and npu is torch_npu
                 and actual_tp is tp and forward_context is context and owner is selected_owner["owner"]
                 and owner_ref==selected_owner["ref"],"same exact original factory supplied handles")
            rank=tp.get_tensor_model_parallel_rank();identity=mods["layout"][1].identity
            ident=identity();capture=mods["layout"][1];callback=mods["callback"];fields=mods["fields"]
            need(type(rank) is int and rank in range(4) and tp.get_tensor_model_parallel_world_size()==4
                 and event["identity"]==ident and owner["rank_bindings"][str(rank)]==ident,
                 "actual all4 assignment owner, not startup labels")
            ingress_bindings.matches_install_owner(owner,rank,ident)
            installer.bound(layout_final_ref)
            final=json.loads(installer.bound(layout_final_ref))
            need(final["original_initialize_returned"] is True and final["exact_owned_restore"] is True
                 and final["primary"] is None and final["secondary"]==[] and final["layout_ref"]==event_ref,
                 "actual original initialize and complete before-bind restoration")
            collector=getattr(publish,"__self__",None)
            need(type(collector) is adapter.Collector and collector.fn is not None
                 and collector.identity==ident and collector.rank==rank,
                 "actual frozen owned collector, no arbitrary callback substituted")
            # Runtime reads avoid unbounded FORMAT journal growth. Live value/type and
            # pointer metadata are still checked; original bound enum proof is retained.
            def runtime_format(tensor):
                before=callback.scalar_tensor(tensor)
                value=collector.fn(tensor)
                code=adapter.FORMAT_POLICY.normalize(value,collector.enum_cls)
                need(code==2 and callback.scalar_tensor(tensor)==before,
                     "actual wrapped enum ND getter, no metadata mutation")
                return code
            zero=spans.snapshot_zeroer(t,runner,event,callback,identity,rank)
            zero_ref=publish("PACKED-QWEN-r%d-ZEROER"%rank,zero)
            need(provider_state["state"]=="consumer_installed"
                 and provider_state["plan_ref"]==owner["explicit_plan_ref"]
                 and provider_state["allocation_ref"]==owner["explicit_allocation_ref"],
                 "actual initialized same-worker explicit provider")
            # Exact state came from this native worker, never JSON supplied tensors.
            need(not hasattr(runner,"_kivi_explicit_provider"),"one explicit provider binding per runner")
            runner._kivi_explicit_provider=provider_state
            views_by_layer={};geometries={}
            for name in sorted(regions):
                proposal=regions[name]
                need(proposal==owner["regions"][name]
                     and proposal["allocation_ref"]==provider_state["allocation_ref"],
                     "same source-bound explicit allocation proposal")
                arena=provider_state["arenas"][name]
                need(type(arena)is mods["lifecycle"].CompactArena and not arena.active,
                     "original actual CompactArena constructor, empty at install")
                views={k:v for k,v in arena.pool.items()if k not in("allocated_bytes","dense_shadow_bytes")}
                geometry=explicit_geometry.geometry(provider_state,event,event_ref,zero_ref,name)
                observed={k:capture.descriptor(v,collector.read)for k,v in views.items()}
                need(observed=={f["name"]:f["descriptor"]for f in geometry["fields"]},
                     "same live original explicit fields at actual install")
                views_by_layer[name]=views;geometries[name]=geometry
            descriptors={n:{f["name"]:f["descriptor"]for f in g["fields"]}for n,g in geometries.items()}
            disjoint=explicit_geometry.consume_rank(owner,event,descriptors,zero)
            disjoint_ref=publish("PACKED-QWEN-r%d-DISJOINT"%rank,disjoint)
            format_ref=publish("PACKED-QWEN-r%d-FORMAT"%rank,
                dict(schema="kivi.actual-packed-format-binding/v1",rank=rank,identity=ident,
                     binding_raw_ref=collector.bind_raw_ref,source=collector.binding,
                     field_call_refs=list(collector.calls),runtime_format_is_enum_checked=True,
                     actual_getter_result_is_runtime_observation=True,model_ready=False,run_authority=False))
            contexts={};geometry_refs={}
            for name in sorted(views_by_layer):
                geometry=geometries[name]
                geometry_ref=publish("PACKED-QWEN-r%d-%s-GEOMETRY"%(rank,name.replace(".","-")),geometry)
                geometry_refs[name]=geometry_ref
                arena=provider_state["arenas"][name]
                batch=producer.PackedBatch(t,dict(kernel=kernel,metadata=metadata,lifecycle=mods["lifecycle"],
                    callback=callback,triton=mods["triton"],tl=mods["tl"]),
                    source_refs=source_refs,device_properties=device_properties,get_format=runtime_format,
                    qualify=qualify,actual_identity=identity,rank=rank,publish=publish)
                contexts[name]=dict(arena=arena,packed_batch=batch,before_bind_ref=event_ref,
                    actual_format_ref=format_ref,geometry_ref=geometry_ref)
            derived=dict(owner)
            derived.update(schema="kivi.actual-packed-installer-owner/v1",
                original_install_input_ref=owner_ref,layout_consumer_ref=disjoint_ref,
                zeroer_writer_receipt_ref=zero_ref,layout_final_ref=layout_final_ref,
                field_geometry_refs=geometry_refs)
            derived_ref=publish("PACKED-QWEN-r%d-INSTALL-OWNER"%rank,derived)
            journal=(raw_journal_module.FirstDecodeJournal(journal_module,publish,identity,rank,derived_ref,event_ref)
                     if capture_raw else journal_module.JournalPublisher(publish,identity,rank,derived_ref,event_ref))
            if capture_raw:
                journal.bind_packed({name:ctx["packed_batch"] for name,ctx in contexts.items()},
                                    producer.PackedBatch,publish)
            restore=installer.install(runner,torch=t,forward_context=forward_context,capture=capture,
                callback=callback,formal=formal,book_module=book,producer_module=producer,
                owner=derived,owner_ref=derived_ref,event=event,event_ref=event_ref,layer_contexts=contexts,
                qualify=qualify,identity=identity,rank=rank,publish=journal,
                writer_guard=functools.partial(explicit_geometry.guard_current,t,callback,identity,rank),
                ingress_bindings=ingress_bindings,
                capture_raw=capture_raw,raw_root=raw_root,
                provenance=provenance,first_decode_capture_only=first_decode_capture_only)
            need(callable(restore),"actual output installer, not shadow callback or silent fallback")
            closed={}
            def close():
                if "ref"not in closed:
                    closed["ref"]=journal.finish(publish("PACKED-QWEN-r%d-FINAL"%rank,restore()))
                return closed["ref"]
            finish_module.install(runner,close,owner["declared_passed_request_ids"],
                source_refs["installer"]["sha256"],publish_final)
            return close
    return prebind.make_worker(native_worker_cls,mods,adapter,PackedInstallBridge(),torch,torch_npu,tp,
        kv_spec,context,layout_owner=layout_owner,layout_owner_ref=layout_owner_ref,layout_mf=layout_mf,
        post_owner=post_owner,post_owner_ref=post_owner_ref,
        resolve_post_owner=initialized_resolver,native_initialize=provider_initialize,
        native_initialize_sha=source_refs["explicit_provider"]["sha256"])

