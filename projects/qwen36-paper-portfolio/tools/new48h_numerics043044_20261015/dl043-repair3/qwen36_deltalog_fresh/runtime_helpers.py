_LOCK = threading.RLock()
_LAYER_AUX = {}
_COUNTS = {}
_EVENT_SEEN = set()
def _event(event, **fields):
    root = os.environ.get("QWEN36_DELTALOG_FRESH_AUDIT")
    if not root:
        raise RuntimeError("enabled DeltaLog requires a fresh audit directory")
    p = Path(root)
    if not p.is_dir():
        raise RuntimeError("audit root must be created by admitted launcher")
    identity = (os.getpid(), event, fields.get("prefix"))
    if event in ("decode_dispatch", "mixed_decode_dispatch", "prefill_materialized", "kernel_abi"):
        with _LOCK:
            if identity in _EVENT_SEEN:
                return
            _EVENT_SEEN.add(identity)
    from vllm.distributed import parallel_state as ps
    # General-plugin registration can precede TP group initialization.
    # Only installation may have rank=None; model/lifecycle events require
    # the actual initialized group, never a fabricated rank0.
    rank = None if event == "plugin_installed" and ps._TP is None else ps.get_tensor_model_parallel_rank()
    data = {"schema": "deltalog.fresh-provider-event/v1", "event": event,
            "pid": os.getpid(), "rank": rank, "time_ns": time.time_ns(), **fields}
    path = p / ("worker-" + str(os.getpid()) + ".jsonl")
    fd = os.open(path, os.O_CREAT | os.O_WRONLY | os.O_APPEND, 0o600)
    try:
        os.write(fd, (json.dumps(data, sort_keys=True, allow_nan=False) + "\n").encode())
    finally:
        os.close(fd)

def _bind(torch, legacy, layer):
    base = layer.kv_cache[1]
    if not base.is_contiguous():
        raise RuntimeError("DeltaLog direct decode needs actual contiguous FP32 base")
    identity = (base.data_ptr(), base.storage_offset(), tuple(base.stride()), tuple(base.shape), base.untyped_storage().data_ptr())
    prior = getattr(layer, "_qwen36_deltalog_base_identity", None)
    existing = getattr(layer, "_qwen36_deltalog_aux", None)
    if prior is not None and prior != identity:
        if existing is not None and bool((existing["length"][:, :, 0] != 0).any().item()):
            raise RuntimeError("live state-log cannot rebind another base view")
        if existing is not None:
            delattr(layer, "_qwen36_deltalog_aux")
    aux = legacy._ensure_aux(torch, layer)
    if aux is None:
        raise RuntimeError("DeltaLog direct decode needs actual contiguous FP32 base")
    layer._qwen36_deltalog_base_identity = identity
    ptr = layer.kv_cache[1].data_ptr()
    _LAYER_AUX[ptr] = (layer, aux)
    return aux

def _copy_descriptors(torch, legacy, mu, original_collect):
    @functools.wraps(original_collect)
    def collect(copy_bufs, kv_cache_config, mamba_state_copy_funcs, mamba_group_ids,
                src_block_idx, dest_block_idx, accept_token_bias, req_state,
                forward_context):
        if accept_token_bias != 0:
            raise RuntimeError("DeltaLog supports non-spec temporal copy only")
        if src_block_idx == dest_block_idx:
            return original_collect(copy_bufs, kv_cache_config,
                mamba_state_copy_funcs, mamba_group_ids, src_block_idx,
                dest_block_idx, accept_token_bias, req_state, forward_context)
        if copy_bufs.offset == 0:
            copy_bufs._deltalog_edges = {}
            copy_bufs._deltalog_copy_events = []
        before = copy_bufs.offset
        original_collect(copy_bufs, kv_cache_config, mamba_state_copy_funcs,
            mamba_group_ids, src_block_idx, dest_block_idx, accept_token_bias,
            req_state, forward_context)
        cursor = before
        for gid in mamba_group_ids:
            block_ids = req_state.block_ids[gid]
            for name in kv_cache_config.kv_cache_groups[gid].layer_names:
                layer = forward_context[name]
                if len(layer.kv_cache) != 2 or len(mamba_state_copy_funcs) != 2:
                    raise RuntimeError("GDN conv/temporal copy inventory drift")
                base = layer.kv_cache[1]
                # Actual native descriptors were generated by the real copy funcs.
                temporal_index = cursor + 1
                source = int(copy_bufs.src_ptrs.np[temporal_index])
                dest = int(copy_bufs.dst_ptrs.np[temporal_index])
                size = int(copy_bufs.sizes.np[temporal_index])
                cursor += 2
                stride_bytes = base.stride(0) * base.element_size()
                natural_bytes = base[0].numel() * base.element_size()
                src, dst = copy_edge(base.data_ptr(), stride_bytes, natural_bytes,
                                     source, dest, size, base.shape[0])
                if src != block_ids[src_block_idx] or dst != block_ids[dest_block_idx]:
                    raise RuntimeError("native temporal pointer/slot owner mismatch")
                aux = _bind(torch, legacy, layer)
                edges = copy_bufs._deltalog_edges.setdefault(base.data_ptr(), [])
                edges.append((src, dst))
                for field in AUX_NAMES:
                    tensor = aux[field]
                    offset = copy_bufs.offset
                    if offset >= len(copy_bufs.sizes.np):
                        raise RuntimeError("extended native copy buffer exhausted")
                    copy_bufs.src_ptrs.np[offset] = tensor[src].data_ptr()
                    copy_bufs.dst_ptrs.np[offset] = tensor[dst].data_ptr()
                    copy_bufs.sizes.np[offset] = tensor[src].numel() * tensor.element_size()
                    copy_bufs.offset += 1
                copy_bufs._deltalog_copy_events.append({
                    "prefix": name, "request_id": req_state.req_id,
                    "source_slot": src, "destination_slot": dst})
    return collect

def install_copy_bridge(torch, legacy, mu):
    original_create = mu.MambaCopyBuffers.create.__func__
    original_collect = mu.collect_mamba_copy_meta
    original_copy = mu.do_mamba_copy_block
    if getattr(mu, "_qwen36_deltalog_mixed_bridge", False):
        raise RuntimeError("duplicate copy bridge install")
    @classmethod
    def create(cls, max_num_reqs, kv_cache_config, copy_funcs, make_buffer):
        obj = original_create(cls, max_num_reqs, kv_cache_config, copy_funcs, make_buffer)
        # Original has two descriptors/layer/request. Seven are needed.
        n = len(obj.sizes.np) * 4
        obj.src_ptrs = make_buffer(n, dtype=torch.int64)
        obj.dst_ptrs = make_buffer(n, dtype=torch.int64)
        obj.sizes = make_buffer(n, dtype=torch.int32)
        return obj
    @functools.wraps(original_copy)
    def copy(copy_bufs):
        if copy_bufs.offset == 0:
            return original_copy(copy_bufs)
        for edges in getattr(copy_bufs, "_deltalog_edges", {}).values():
            validate_edges(edges)
        result = original_copy(copy_bufs)
        # Native batch_memcpy is asynchronous. This bridge executes before
        # _model_forward (actual source-pinned runner callsite), not in capture.
        # A committed event requires actual current-stream completion.
        torch.npu.current_stream().synchronize()
        # A native single batch_memcpy kernel owns base+all five aux arrays.
        # Stream completion of that kernel is the transaction boundary.
        for event in getattr(copy_bufs, "_deltalog_copy_events", []):
            _event("copy_aux_committed", native_stream_completed=True, aux_names=list(AUX_NAMES), **event)
        return result
    mu.MambaCopyBuffers.create = create
    mu.collect_mamba_copy_meta = _copy_descriptors(torch, legacy, mu, original_collect)
    mu.do_mamba_copy_block = copy
    mu._qwen36_deltalog_mixed_bridge = True

def execute_mixed_core(torch, legacy, gdn, specialized, original, self,
                       mixed_qkv, b, a, core, emit=None):
    context = gdn.get_forward_context()
    metadata_map = context.attn_metadata
    if metadata_map is None:
        return original(self, mixed_qkv, b, a, core)
    meta = metadata_map[self.prefix]
    if meta.spec_sequence_masks is not None:
        raise RuntimeError("speculative DeltaLog lifecycle unsupported")
    if getattr(self, "tp_size", None) != 4 or gdn.get_pcp_group().world_size != 1:
        raise RuntimeError("reviewed TP4/PCP1 only")
    if meta.num_decode_tokens != meta.num_decodes or meta.num_decodes > 16:
        raise RuntimeError("non-spec one-token decode metadata required")
    aux = _bind(torch, legacy, self)
    emit = emit or (lambda *args, **kwargs: None)
    if meta.num_prefills:
        # Prefill consumes a dense initial state. Decode slots retain their
        # log through the same mixed native convolution/prefill turn.
        ids = meta.prefill_state_indices
        legacy._flush_slots(torch, self, aux, ids, "prefill_initial_state_only")
        emit("prefill_materialized", prefix=self.prefix,
               prefill_slots=int(ids.numel()), decode_slots_materialized=0)
    result = specialized(self, mixed_qkv, b, a, core)
    if meta.num_prefills:
        legacy._reset_selected(aux, meta.prefill_state_indices)
    if meta.num_decodes:
        emit("mixed_decode_dispatch" if meta.num_prefills else "decode_dispatch",
               prefix=self.prefix, tokens=int(meta.num_decodes),
               materialized_decode_slots=0, capacity=7)
        emit("graph_static_abi", prefix=self.prefix,
               consumer="qwen36_deltalog_key_projection::decode",
               phase_source="device log_length; append/merge in same kernel",
               input_pointers={n: aux[n].data_ptr() for n in AUX_NAMES})
    return result
